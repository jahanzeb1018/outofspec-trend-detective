"""Shapes for the animated "How it works" page (web/src/content/journeyGeo.ts).

Spain and Portugal outlines, the 159 NASA grid squares along the railway (with today's heat level), the 24 routes and the
Seville series of days at 40 °C, projected into an 800 x 450 drawing. Simplified: an illustration, not a map.
Run after process.py.
"""
from __future__ import annotations

import json
import math

from shapely.geometry import LineString, shape

import config as C

LON0, LON1, LAT0, LAT1 = -9.6, 3.5, 35.8, 44.0
KX = math.cos(math.radians(40.0))
H = 400.0
SCALE = H / (LAT1 - LAT0)
W = (LON1 - LON0) * KX * SCALE
OX = (800 - W) / 2
OY = 25.0


def xy(lon: float, lat: float) -> tuple[float, float]:
    return OX + (lon - LON0) * KX * SCALE, OY + (LAT1 - lat) * SCALE


def ring_path(coords) -> str:
    pts = [xy(x, y) for x, y in coords]
    return "M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z"


def outline(geom) -> str:
    g = geom.simplify(0.04, preserve_topology=True)
    polys = [g] if g.geom_type == "Polygon" else list(g.geoms)
    parts = []
    for p in polys:
        if p.area < 0.05:  # drop tiny islands
            continue
        parts.append(ring_path(p.exterior.coords))
    return "".join(parts)


def main() -> None:
    ib = json.loads((C.OUT / "iberia.geojson").read_text(encoding="utf-8"))
    out: dict = {}
    for f in ib["features"]:
        name = f["properties"]["name"]
        if name in ("Spain", "Portugal"):
            out[name] = outline(shape(f["geometry"]))
    cells = json.loads((C.OUT / "cells.geojson").read_text(encoding="utf-8"))
    summary = json.loads((C.OUT / "summary.json").read_text(encoding="utf-8"))
    sq = []
    for f in sorted(cells["features"], key=lambda f: (-f["properties"]["lat"], f["properties"]["lon"])):
        p = f["properties"]
        x0, y0 = xy(p["lon"] - 0.3125, p["lat"] + 0.25)
        x1, y1 = xy(p["lon"] + 0.3125, p["lat"] - 0.25)
        late = summary["cells"][p["c"]]["HOT40"]["late"] or 0
        lvl = 0 if late < 0.5 else 1 if late <= 5 else 2 if late <= 10 else 3 if late <= 20 else 4
        sq.append([round(x0, 1), round(y0, 1), round(x1 - x0, 1), round(y1 - y0, 1), lvl])
    routes = json.loads((C.OUT / "routes.json").read_text(encoding="utf-8"))
    paths = []
    for r in routes:
        ls = LineString(r["geometry"]).simplify(0.03)
        pts = [xy(x, y) for x, y in ls.coords]
        paths.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts))
    annual = json.loads((C.OUT / "annual.json").read_text(encoding="utf-8"))
    sev = annual["values"]["HOT40"]["37.50_-5.625"]
    sx, sy = xy(-5.98, 37.39)
    mx, my = xy(-3.70, 40.42)
    ts = f'''// Generated by pipeline/journey_geo.py: shapes for the "How it works" animation (an illustration, not a map).
export const J_SPAIN = "{out["Spain"]}";
export const J_PORTUGAL = "{out["Portugal"]}";
/** x, y, w, h, heat level today (days at 40 °C a year: 0, 1-5, 6-10, 11-20, 21+) */
export const J_CELLS: [number, number, number, number, number][] = {json.dumps(sq, separators=(",", ":"))};
export const J_ROUTES: string[] = {json.dumps(paths, separators=(",", ":"))};
/** Days at 40 °C a year near Seville (NASA POWER, grid square 37.5 N, 5.625 W), {annual["years"][0]}-{annual["years"][-1]}. */
export const J_SEVILLE: number[] = {json.dumps(sev)};
export const J_SEVILLE_X = {sx:.1f};
export const J_SEVILLE_Y = {sy:.1f};
export const J_MADRID_X = {mx:.1f};
export const J_MADRID_Y = {my:.1f};
'''
    dst = C.OUT.parent.parent / "src" / "content" / "journeyGeo.ts"
    dst.write_text(ts, encoding="utf-8")
    print("journeyGeo.ts", round(dst.stat().st_size / 1024), "KB,", len(sq), "squares,", len(paths), "routes")


if __name__ == "__main__":
    main()
